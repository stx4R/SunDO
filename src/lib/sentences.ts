/**
 * 마침표 기준 줄바꿈 — W-21 P-8 ②.
 *
 * 🔴 **문구 데이터를 건드리지 않는다.** §8.10 사전의 문자열은 한 글자도 그대로 두고
 * **렌더할 때만** 나눈다. 사전이 정본이고 줄바꿈은 표시 규칙이다.
 *
 * 🔴 **마침표 뒤에 공백이 있을 때만 나눈다.** 그래서 소수(`0.5`)·판본(`2.0`)·
 * 도메인(`lukeed.com`)·URL(`…/LICENSE-2.0`)은 **정의상 걸리지 않는다** — 그것들은
 * 마침표 뒤가 공백이 아니다.
 * 🔬 W-21 전수 조사: 대상 범위(확인 모달 6건 + S2 재가입 안내 1건) 안에 마침표 예외는
 * **0건**이다. 예외를 가진 문자열은 전부 `lib/policy.ts`(정책 문서 본문)에 있고
 * 그 화면은 이 함수의 소비자가 아니다 — 긴 문서를 문장마다 끊으면 읽을 수 없다.
 *
 * ⚠ `?`·`!`로는 나누지 않는다. 요구가 「마침표 기준」이고, 사전의 의문문은 전부
 * 문자열의 **마지막**이라 나눌 것이 없다(`계속할까요?`·`재발급할까요?`·`로그아웃할까요?`).
 */
export function splitSentences(text: string): string[] {
  return text.split(/(?<=\.)\s+/).filter((line) => line.length > 0)
}
