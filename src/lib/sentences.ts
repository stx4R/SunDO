/**
 * 문장 부호 기준 줄바꿈 — W-21 P-8 ② · **W-23 A-6(B-08)에서 `?`·`!`가 더해졌다.**
 *
 * 🔴 **문구 데이터를 건드리지 않는다.** §8.10 사전의 문자열은 한 글자도 그대로 두고
 * **렌더할 때만** 나눈다. 사전이 정본이고 줄바꿈은 표시 규칙이다.
 *
 * 🔴 **구분자 뒤에 공백이 있을 때만 나눈다.** 그래서 소수(`0.5`)·판본(`2.0`)·
 * 도메인(`lukeed.com`)·URL(`…/LICENSE-2.0`)은 **정의상 걸리지 않는다** — 그것들은
 * 마침표 뒤가 공백이 아니다. 🔴 **`?`·`!`도 같은 장치에 그대로 올라탄다** —
 * 새 예외 처리를 만들지 않았고, 그것이 지시서가 요구한 「현재 `.` 처리와 같은 방식」이다.
 *
 * 이 한 가지 성질에서 요구 셋이 **동시에** 따라 나온다.
 * ① **문자열 끝의 구분자 뒤에는 줄바꿈이 없다** — 뒤에 공백이 없으므로 매치 자체가 없다.
 *    (`로그아웃할까요?`·`계속할까요?`는 그대로 한 줄이다.)
 * ② **연속 구분자에서 이중 줄바꿈이 없다** — `?!`·`...`는 구분자 **사이에** 공백이 없어
 *    매치가 마지막 구분자 뒤 한 번뿐이다. `\s+`가 공백 덩어리를 통째로 먹는 것도 같은 방향이다.
 * ③ 소수·약어는 ①과 같은 이유로 걸리지 않는다.
 *
 * 🔬 W-23 전수 조사(§1-8): 소비자는 `ConfirmModal`(모달 본문 7건)과 `Signup`(EC-39) 둘뿐이고,
 * 그 범위에서 **실제로 줄이 갈리는 문자열은 MD-04 하나**다(`이 기록을 삭제할까요? 삭제 이력은…`).
 * `!`는 사전 전체에 **0건**이라 지금은 도달하지 않는 경로다 — 그래도 넣는다.
 * 그 밖의 문자열은 before/after가 같다(보고서 §5 표).
 */
export function splitSentences(text: string): string[] {
  return text.split(/(?<=[.?!])\s+/).filter((line) => line.length > 0)
}
